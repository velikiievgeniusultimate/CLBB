//! Generate equivalent C kernels for QEMU's existing QARMA implementation.
//! No runtime Rust/C bridge; portable ANF/SWAR plus gated full-state SSSE3.
use std::fmt::Write;
#[path = "vector-state.rs"]
mod vector_state;

const SUB: [u8; 16] = [0xb, 6, 8, 0xf, 0xc, 0, 9, 0xe, 3, 7, 4, 5, 0xd, 2, 1, 0xa];

fn substitution(out: &mut String, name: &str, sub: &[u8; 16]) {
    writeln!(out, "static uint64_t {name}(uint64_t i)\n{{").unwrap();
    out.push_str("    /* Generated ANF: sixteen independent nibbles, with no\n\
                  \x20    * input-dependent memory lookup or branch. */\n");
    out.push_str("    const uint64_t mask = UINT64_C(0x1111111111111111);\n");
    let mut outputs = Vec::new();
    let mut used = [false; 16];
    for bit in 0..4 {
        let mut coefficients = sub.map(|value| (value >> bit) & 1);
        for variable in 0..4 {
            for term in 0..16 {
                if term & (1 << variable) != 0 {
                    coefficients[term] ^= coefficients[term ^ (1 << variable)];
                }
            }
        }
        let terms: Vec<_> = (0..16).filter(|&term| coefficients[term] != 0).collect();
        for &term in &terms { used[term] = true; }
        outputs.push(terms);
    }
    for term in (1_usize..16).rev() {
        if used[term] && term.count_ones() > 1 {
            used[term & (term - 1)] = true;
            used[term & term.wrapping_neg()] = true;
        }
    }
    for variable in 0..4 {
        writeln!(out, "    uint64_t v{} = (i >> {variable}) & mask;", 1 << variable).unwrap();
    }
    for (term, &needed) in used.iter().enumerate().skip(1) {
        if needed && term.count_ones() > 1 {
            writeln!(out, "    uint64_t v{term} = v{} & v{};", term & (term - 1), term & term.wrapping_neg()).unwrap();
        }
    }
    out.push_str("\n    return ");
    for (bit, terms) in outputs.iter().enumerate() {
        if bit != 0 { out.push_str(" ^\n           "); }
        out.push_str("((");
        for (index, &term) in terms.iter().enumerate() {
            if index != 0 { out.push_str(" ^ "); }
            if term == 0 { out.push_str("mask"); }
            else { write!(out, "v{term}").unwrap(); }
        }
        write!(out, ") << {bit})").unwrap();
    }
    out.push_str(";\n}\n");
}

fn main() {
    let mut inv = [0; 16];
    for (i, &v) in SUB.iter().enumerate() {
        inv[v as usize] = i as u8;
    }
    for x in 0..256 {
        let y = (SUB[x & 15] | SUB[x >> 4] << 4) as usize;
        assert_eq!(inv[y & 15] | inv[y >> 4] << 4, x as u8);
    }
    let mut out = String::new();
    substitution(&mut out, "pac_sub", &SUB);
    substitution(&mut out, "pac_inv_sub", &inv);
    out.push_str(
        "static uint64_t pac_mult(uint64_t i)\n\
         {\n\
         \x20   /* Generated by CLBB tools/pauth-audit/generate.rs. Rotate each\n\
         \x20    * nibble in parallel, then mix all four 16-bit rows at once.\n\
         \x20    * Rows: r1[3]^r2[2]^r1[1], r2[3]^r1[2]^r1[0],\n\
         \x20    *       r1[3]^r1[1]^r2[0], r1[2]^r2[1]^r1[0]. */\n\
         \x20   uint64_t r1 = ((i << 1) & UINT64_C(0xeeeeeeeeeeeeeeee)) |\n\
         \x20                 ((i >> 3) & UINT64_C(0x1111111111111111));\n\
         \x20   uint64_t r2 = ((i << 2) & UINT64_C(0xcccccccccccccccc)) |\n\
         \x20                 ((i >> 2) & UINT64_C(0x3333333333333333));\n\n\
         \x20   return ((r1 << 16) | (r1 >> 48)) ^\n\
         \x20          ((r1 << 48) | (r1 >> 16)) ^\n\
         \x20          ((r2 << 32) | (r2 >> 32));\n\
         }\n",
    );
    print!("{out}");
    println!("\n#if defined(__x86_64__) && defined(__GNUC__)\n#include <tmmintrin.h>");
    vector_state::emit();
    println!("#endif");
}
