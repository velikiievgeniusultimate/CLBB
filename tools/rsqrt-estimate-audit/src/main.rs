use clbb_rsqrt_estimate_audit::{COUNT, FIRST, LAST, TABLE};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;
fn error(s: &str) -> Box<dyn std::error::Error> {
    io::Error::other(s).into()
}
fn run(command: &mut Command) -> Result<Output> {
    let out = command.output()?;
    if !out.status.success() {
        return Err(error(&format!(
            "Command failed: {:?}\n{}\n{}",
            command,
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(out)
}
fn extract_function(source: &str, name: &str) -> Result<String> {
    let marker = format!("static int {name}(");
    let start = source
        .find(&marker)
        .ok_or_else(|| error("Production function signature changed"))?;
    let body = start
        + source[start..]
            .find('{')
            .ok_or_else(|| error("Missing function body"))?;
    let mut depth = 0u32;
    for (offset, ch) in source[body..].char_indices() {
        match ch {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return Ok(source[start..body + offset + 1].to_owned());
                }
            }
            _ => {}
        }
    }
    Err(error("Unterminated production function"))
}
fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c < ' ' => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
fn header() -> String {
    let mut out = String::from(
        "/* Generated by the std-only Rust finite-domain audit.\n * Values exactly match all 384 valid inputs of do_recip_sqrt_estimate.\n * No floating-point approximation or runtime initialization. */\n#ifndef CLBB_EXACT_RSQRT_TABLE_H\n#define CLBB_EXACT_RSQRT_TABLE_H\n#include <assert.h>\n#include <stdint.h>\nstatic const uint8_t clbb_rsqrt_estimate_minus_256[384] = {\n",
    );
    for row in TABLE.chunks(16) {
        out.push_str("    ");
        for (column, n) in row.iter().enumerate() {
            if column != 0 {
                out.push(' ');
            }
            out.push_str(&format!("{n},"));
        }
        out.push('\n');
    }
    out.push_str("};\nstatic inline int clbb_exact_rsqrt_lookup(int a)\n{\n    assert(128 <= a && a < 512);\n    return 256 + clbb_rsqrt_estimate_minus_256[a - 128];\n}\n#endif\n");
    format!("{}\n{}", include_str!("qemu-vfp-notice.inc"), out)
}
fn c_source(notice: &str, original: &str, current: &str) -> String {
    format!(
        "{notice}\n/* Oracle below is extracted unchanged from target/arm/vfp_helper.c. */\n#define _POSIX_C_SOURCE 200809L\n#include <assert.h>\n#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n#include <time.h>\n#include \"rsqrt-table.h\"\n{original}\n{current}\n{}",
        include_str!("benchmark.inc")
    )
}
fn stats() -> (u64, u64, u64) {
    let mut total = 0;
    let mut max_steps = 0;
    let mut max_product = 0;
    for input in FIRST..=LAST {
        let a = if input < 256 {
            input * 2 + 1
        } else {
            (((input >> 1) << 1) + 1) * 2
        };
        let mut b = 512u64;
        while u64::from(a) * (b + 1) * (b + 1) < 1 << 28 {
            b += 1;
        }
        total += b - 512;
        max_steps = max_steps.max(b - 512);
        max_product = max_product.max(u64::from(a) * (b + 1) * (b + 1));
    }
    (total, max_steps, max_product)
}
fn main_run() -> Result<()> {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let root = dir
        .parent()
        .and_then(Path::parent)
        .ok_or_else(|| error("Missing root"))?;
    let mut iterations = 2_000_000u64;
    let mut repeats = 7u32;
    let mut compiler = "cc".to_owned();
    let mut output = dir.join("artifacts");
    let mut check = false;
    let mut generate_only = false;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--iterations" => {
                iterations = args
                    .next()
                    .ok_or_else(|| error("Missing iterations"))?
                    .parse()?
            }
            "--repeats" => {
                repeats = args
                    .next()
                    .ok_or_else(|| error("Missing repeats"))?
                    .parse()?
            }
            "--compiler" => compiler = args.next().ok_or_else(|| error("Missing compiler"))?,
            "--output" => {
                output = PathBuf::from(args.next().ok_or_else(|| error("Missing output"))?)
            }
            "--check" => {
                check = true;
                iterations = 10_000;
                repeats = 1;
            }
            "--generate-only" => generate_only = true,
            "--help" => {
                println!(
                    "clbb-rsqrt-estimate-audit [--iterations 2000000] [--repeats 7] [--compiler cc] [--output artifacts] [--check | --generate-only]"
                );
                return Ok(());
            }
            _ => return Err(error("Unknown option")),
        }
    }
    if !(10_000..=1_000_000_000).contains(&iterations) || !(1..=31).contains(&repeats) {
        return Err(error("Invalid iteration/repetition range"));
    }
    if check && output == dir.join("artifacts") {
        output = output.join("check");
    }
    fs::create_dir_all(&output)?;
    let output = output.canonicalize()?;
    let production = root.join("src/nb-qemu/qemu/target/arm/vfp_helper.c");
    let source = fs::read_to_string(&production)?;
    let current = extract_function(&source, "do_recip_sqrt_estimate")?;
    let original = extract_function(
        include_str!("oracle-vfp-helper.c"),
        "do_recip_sqrt_estimate",
    )?;
    if current != original && current.trim() != include_str!("optimized-helper.inc").trim() {
        return Err(error(
            "Production helper differs from both frozen oracle and audited lookup; re-audit required",
        ));
    }
    if check && current.trim() != include_str!("optimized-helper.inc").trim() {
        return Err(error(
            "Build check requires the audited production lookup helper",
        ));
    }
    let current = current.replace(
        "do_recip_sqrt_estimate",
        "production_current_rsqrt_estimate",
    );
    let notice_end = source
        .find("*/")
        .ok_or_else(|| error("Missing upstream copyright notice"))?
        + 2;
    fs::write(output.join("rsqrt-table.h"), header())?;
    fs::write(
        output.join("extracted-oracle-and-benchmark.c"),
        c_source(&source[..notice_end], &original, &current),
    )?;
    if generate_only {
        println!(
            "EXACT_RSQRT_GENERATED {}",
            output.join("rsqrt-table.h").display()
        );
        return Ok(());
    }
    if check {
        let committed = production.with_file_name("rsqrt-estimate-table.h");
        if fs::read(&committed)? != header().as_bytes() {
            return Err(error(
                "Committed QEMU header differs from Rust const generator",
            ));
        }
        if !source.contains("#include \"rsqrt-estimate-table.h\"") {
            return Err(error("QEMU source is missing generated table include"));
        }
    }
    let archive = dir.join("target/release/libclbb_rsqrt_estimate_audit.a");
    if !archive.exists() {
        return Err(error(
            "Build --release (both lib and binary) before running generator",
        ));
    }
    let source_hash = run(Command::new("sha256sum").arg("--").arg(&production))?;
    let source_hash = String::from_utf8(source_hash.stdout)?
        .split_whitespace()
        .next()
        .unwrap_or("")
        .to_owned();
    let compiler_version = run(Command::new(&compiler).arg("--version"))?;
    let compiler_version = String::from_utf8(compiler_version.stdout)?
        .lines()
        .next()
        .unwrap_or("")
        .to_owned();
    if check {
        let binary = output.join("exhaustive-ubsan");
        run(Command::new(&compiler)
            .args([
                "-std=c11",
                "-O2",
                "-fno-lto",
                "-fsanitize=undefined",
                "-fno-sanitize-recover=all",
                "-Wall",
                "-Wextra",
                "-Werror",
            ])
            .arg(output.join("extracted-oracle-and-benchmark.c"))
            .arg(&archive)
            .arg("-o")
            .arg(&binary))?;
        let verified = run(Command::new(binary).arg("10000").arg("1"))?;
        fs::write(output.join("exhaustive-ubsan.json"), verified.stdout)?;
        println!(
            "EXACT_RSQRT_BUILD_CHECK_OK const_header=identical production_helper=audited valid_inputs=384 u32_prefix_endpoints=1024 assertions=enabled UBSan=passed"
        );
        return Ok(());
    }
    let mut builds = Vec::new();
    for optimization in ["-O2", "-O3"] {
        let binary = output.join(format!("benchmark{}", optimization));
        run(Command::new(&compiler)
            .arg("-std=c11")
            .arg(optimization)
            .args(["-DNDEBUG", "-fno-lto", "-Wall", "-Wextra", "-Werror"])
            .arg(output.join("extracted-oracle-and-benchmark.c"))
            .arg(&archive)
            .arg("-o")
            .arg(&binary))?;
        let measured = run(Command::new(&binary)
            .arg(iterations.to_string())
            .arg(repeats.to_string()))?;
        let text = String::from_utf8(measured.stdout)?;
        print!("{optimization} {text}");
        fs::write(output.join(format!("benchmark{optimization}.json")), &text)?;
        builds.push(format!(
            "{{\"optimization\":{},\"results\":{}}}",
            quote(optimization),
            text.trim()
        ));
    }
    let (steps, max_steps, max_product) = stats();
    let cpu = fs::read_to_string("/proc/cpuinfo")
        .unwrap_or_default()
        .lines()
        .find_map(|line| {
            line.strip_prefix("model name")
                .and_then(|s| s.split_once(':').map(|(_, v)| v.trim().to_owned()))
        })
        .unwrap_or_default();
    let result = format!(
        "{{\n\"source\":{},\"source_sha256\":{},\"compiler\":{},\"cpu\":{},\"table_bytes\":{COUNT},\"valid_input_first\":{FIRST},\"valid_input_last\":{LAST},\"original_total_loop_iterations_all_inputs\":{steps},\"original_max_loop_iterations\":{max_steps},\"largest_original_multiply\":{max_product},\"runs\":[{}],\"limitations\":{}\n}}\n",
        quote(&production.to_string_lossy()),
        quote(&source_hash),
        quote(&compiler_version),
        quote(&cpu),
        builds.join(","),
        quote(
            "Isolated hot microbenchmark under concurrent desktop/game load. Does not measure end-to-end game FPS; call overhead and input distribution affect results. QEMU runtime is not built or installed by this tool. Frozen C oracle retains its upstream LGPL notice. No fast-math flags or floating-point arithmetic are used."
        )
    );
    fs::write(output.join("report.json"), result)?;
    println!(
        "EXACT_RSQRT_AUDIT_OK inputs={COUNT} table_bytes={COUNT} max_loop_steps={max_steps} report={}",
        output.join("report.json").display()
    );
    Ok(())
}
fn main() {
    if let Err(e) = main_run() {
        eprintln!("EXACT_RSQRT_AUDIT_ERROR {e}");
        std::process::exit(1)
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn extracts_only_requested_function() {
        let s = "static int before(int a) {return a;}\nstatic int target(int a) {if(a){a++;}return a;}\nstatic int after(int b){return b;}";
        assert_eq!(
            extract_function(s, "target").unwrap(),
            "static int target(int a) {if(a){a++;}return a;}"
        );
        assert!(extract_function(s, "missing").is_err());
    }
    #[test]
    fn generation_has_384_bytes_and_no_fp() {
        assert!(header().contains("uint8_t clbb_rsqrt_estimate_minus_256[384]"));
        assert!(!header().contains("sqrt("));
        assert!(stats().2 < i32::MAX as u64);
    }
}
